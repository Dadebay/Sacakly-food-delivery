-- Delivery pricing is backend-owned. Existing clients without an etrap keep
-- the legacy 15 TMT / free-from-150 TMT behavior through DeliverySettings.
CREATE TABLE "DeliverySettings" (
    "id" VARCHAR(40) NOT NULL DEFAULT 'default',
    "fallbackPrice" DECIMAL(12,2) NOT NULL DEFAULT 15,
    "fallbackFreeDeliveryThreshold" DECIMAL(12,2) DEFAULT 150,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "DeliverySettings_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "Welayat" (
    "id" INTEGER NOT NULL,
    "nameEn" VARCHAR(160),
    "nameRu" VARCHAR(160) NOT NULL,
    "nameTk" VARCHAR(160) NOT NULL,
    "sortOrder" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "Welayat_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "Etrap" (
    "id" INTEGER NOT NULL,
    "welayatId" INTEGER NOT NULL,
    "nameEn" VARCHAR(240),
    "nameRu" VARCHAR(240) NOT NULL,
    "nameTk" VARCHAR(240) NOT NULL,
    "queuePosition" INTEGER,
    "price" DECIMAL(12,2) NOT NULL DEFAULT 15,
    "freeDeliveryThreshold" DECIMAL(12,2) DEFAULT 150,
    "isDeliveryEnabled" BOOLEAN NOT NULL DEFAULT false,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "Etrap_pkey" PRIMARY KEY ("id")
);

ALTER TABLE "UserAddress"
    ADD COLUMN "deliveryEtrapId" INTEGER;

ALTER TABLE "Order"
    ADD COLUMN "deliveryEtrapId" INTEGER,
    ADD COLUMN "deliveryWelayatName" VARCHAR(160),
    ADD COLUMN "deliveryEtrapName" VARCHAR(240);

CREATE INDEX "Welayat_sortOrder_nameRu_idx" ON "Welayat"("sortOrder", "nameRu");
CREATE INDEX "Etrap_welayatId_isDeliveryEnabled_queuePosition_nameRu_idx" ON "Etrap"("welayatId", "isDeliveryEnabled", "queuePosition", "nameRu");
CREATE INDEX "UserAddress_deliveryEtrapId_idx" ON "UserAddress"("deliveryEtrapId");
CREATE INDEX "Order_deliveryEtrapId_idx" ON "Order"("deliveryEtrapId");

ALTER TABLE "Etrap" ADD CONSTRAINT "Etrap_welayatId_fkey"
    FOREIGN KEY ("welayatId") REFERENCES "Welayat"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "UserAddress" ADD CONSTRAINT "UserAddress_deliveryEtrapId_fkey"
    FOREIGN KEY ("deliveryEtrapId") REFERENCES "Etrap"("id") ON DELETE SET NULL ON UPDATE CASCADE;
ALTER TABLE "Order" ADD CONSTRAINT "Order_deliveryEtrapId_fkey"
    FOREIGN KEY ("deliveryEtrapId") REFERENCES "Etrap"("id") ON DELETE SET NULL ON UPDATE CASCADE;

